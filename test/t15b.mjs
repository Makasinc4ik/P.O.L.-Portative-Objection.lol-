import { _electron as electron } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const ROOT = '/home/claude/oo', OUT = ROOT + '/test/out15';
const app = await electron.launch({ executablePath: process.env.EL || (ROOT + '/node_modules/electron/dist/electron'), args: ['--no-sandbox', ROOT], env: { ...process.env, OO_LIBRARY: '/tmp/fresh/Library' } });
const win = await app.firstWindow();
const logs = [];
win.on('pageerror', (e) => logs.push('[pageerror] ' + e.stack));
await win.setViewportSize({ width: 1500, height: 950 }).catch(() => {});
await win.waitForTimeout(2500);
for (let i = 0; i < 3; i++) { await win.keyboard.press('Escape'); await win.waitForTimeout(150); }
await win.evaluate(() => { App.project.aliases = [{ from: '', to: '' }]; [...document.querySelectorAll('button')].find((b) => b.textContent.trim() === 'Настройки проекта')?.click(); });
await win.waitForTimeout(500);
const inp = win.locator('.modal-wrap input[placeholder^="Имя на табличке"]').first();
await inp.scrollIntoViewIfNeeded();
await inp.click();
await win.waitForTimeout(200);
for (let i = 0; i < 18; i++) await win.keyboard.press('ArrowDown');
await win.waitForTimeout(150);
const R = await win.evaluate(() => { const l = document.querySelector('.combo-list:not(.hidden)'); return l && { n: l.querySelectorAll('.combo-item').length, st: l.scrollTop, act: l.querySelector('.active')?.textContent, heads: [...l.querySelectorAll('.combo-head')].map((x) => x.textContent) }; });
await win.screenshot({ path: OUT + '/combo-keys.png' });
await win.keyboard.press('Enter');
await win.waitForTimeout(200);
R.picked = await win.evaluate(() => App.project.aliases[0].from);
await inp.click(); await win.keyboard.type('ph');
await win.waitForTimeout(150);
R.filtered = await win.evaluate(() => [...document.querySelectorAll('.combo-list:not(.hidden) .combo-item')].map((x) => x.textContent).slice(0, 5));
await win.keyboard.press('Escape');
await win.waitForTimeout(150);
R.modalStillOpen = await win.evaluate(() => !!document.querySelector('.modal-wrap'));
console.log(JSON.stringify(R), logs.join('\n'));
await app.close();

import { _electron as electron } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const ROOT = '/home/claude/oo';
const app = await electron.launch({ executablePath: ROOT + '/node_modules/electron/dist/electron', args: ['--no-sandbox', ROOT], env: { ...process.env, OO_LIBRARY: '/tmp/fresh/Library' } });
const win = await app.firstWindow();
const logs = [];
win.on('pageerror', (e) => logs.push('[pageerror] ' + e.message));
win.on('console', (m) => { if (m.type() === 'error') logs.push(m.text()); });
await win.waitForTimeout(2500);
await win.evaluate(() => document.querySelectorAll('.modal-wrap').forEach((m) => m.remove()));
await win.evaluate(() => document.querySelector('#btnLibrary, [data-act=library]')?.click());
await win.evaluate(() => { [...document.querySelectorAll('button, a')].find((b) => b.textContent.trim() === 'Библиотека')?.click(); });
await win.waitForTimeout(1500);
const names = () => win.evaluate(() => [...document.querySelectorAll('.modal-wrap .grid .card .cap')].slice(0, 6).map((c) => c.childNodes[0].textContent));
const before = await names();
const r = await win.evaluate(async () => {
  const s = [...document.querySelectorAll('.modal-wrap select')].find((x) => [...x.options].some((o) => o.value === 'name-desc'));
  if (!s) return 'no select';
  s.value = 'name-desc'; s.dispatchEvent(new Event('change', { bubbles: true }));
  return s.outerHTML.slice(0, 200);
});
await win.waitForTimeout(800);
const after = await names();
console.log(JSON.stringify({ before, r, after }), logs);
await app.close();

// Проверка обновлений: сравнение версий, окно (подменённый ответ), реальный запрос к GitHub
import { _electron as electron } from '/opt/npm-tools/node_modules/playwright/index.mjs';
import fs from 'fs';
const ROOT = '/home/claude/oo', OUT = ROOT + '/test/out25';
fs.mkdirSync(OUT, { recursive: true });
const app = await electron.launch({ executablePath: process.env.EL || (ROOT + '/node_modules/electron/dist/electron'), args: ['--no-sandbox', ROOT], env: { ...process.env, OO_LIBRARY: '/tmp/fresh/Library' } });
const win = await app.firstWindow();
const logs = [];
win.on('pageerror', (e) => logs.push('[pageerror] ' + e.stack));
await win.setViewportSize({ width: 1300, height: 850 }).catch(() => {});
await win.waitForTimeout(2500);
const close = () => win.evaluate(() => document.querySelectorAll('.modal-wrap').forEach((m) => m.remove()));
await close();
const R = {};
R.cmp = await app.evaluate(() => { const c = global.__ooVerCmp; return [c('1.1.0', '1.0.0'), c('v1.0.0', '1.0.0'), c('1.0.10', '1.0.9'), c('Release 1.2', '1.10.0'), c('0.9.6', '1.0.0')]; });
R.real = await win.evaluate(() => window.api.checkUpdate()); if (R.real.notes) R.real.notes = R.real.notes.slice(0, 40);
await win.evaluate(() => window.App.showUpdateDialog({ ok: true, current: '1.0.0', latest: '1.1.0', newer: true, name: 'Release 1.1.0', url: 'https://github.com/x/y/releases/tag/v1.1.0', notes: 'Несколько фильтров на кадр\nКонтраст и насыщенность\nПроверка обновлений', asset: { name: 'ObjectionOfflineLinux64_Release1.1.0.AppImage', url: 'https://example.invalid/a', size: 120e6 } }));
await win.waitForTimeout(300);
await win.screenshot({ path: OUT + '/newer.png' });
await close();
await win.evaluate(() => window.App.showUpdateDialog({ ok: true, current: '1.1.0', latest: '1.1.0', newer: false }));
await win.waitForTimeout(200);
R.same = await win.evaluate(() => document.querySelector('.modal-body').textContent);
await close();
await win.locator('[data-menu="file"]').click();
R.menu = await win.locator('[data-act="update"]').textContent();
await win.locator('[data-act="update"]').click();
await win.waitForTimeout(4000);
R.menuDialog = await win.evaluate(() => document.querySelector('.modal-body')?.textContent);
await win.screenshot({ path: OUT + '/menu.png' });
console.log(JSON.stringify(R, null, 1));
console.log(logs.join('\n'));
await app.close();

// Android-сборка на экране телефона: снимки основных экранов
import { _electron as electron } from '/opt/npm-tools/node_modules/playwright/index.mjs';
import fs from 'fs';
const ROOT = '/home/claude/oo', OUT = ROOT + '/test/outA3' + (process.env.SUF || '');
fs.mkdirSync(OUT, { recursive: true });
const TR = '/tmp/oo-android2';
const W = process.env.OO_W || '412', H = process.env.OO_H || '915';
const app = await electron.launch({ executablePath: ROOT + '/node_modules/electron/dist/electron', args: ['--no-sandbox', ROOT + '/android/harness'], env: { ...process.env, OO_TEST_ROOT: TR, OO_W: W, OO_H: H } });
const win = await app.firstWindow();
const logs = [];
win.on('pageerror', (e) => logs.push('[pageerror] ' + e.stack));
await win.waitForTimeout(3500);
const shot = async (n) => { await win.waitForTimeout(500); await win.screenshot({ path: `${OUT}/${n}.png` }); };
const esc = async () => { await win.evaluate(() => window.__ooBack && window.__ooBack()); await win.waitForTimeout(300); };
await win.screenshot({ path: `${OUT}/00-start.png` });
for (let i = 0; i < 3; i++) await esc();
await win.locator('#btnScenes').click(); await win.waitForTimeout(800);
await win.locator('.scene-row').first().click(); await win.waitForTimeout(2500);
for (let i = 0; i < 2; i++) await esc();
await win.locator('.frame textarea').nth(2).click({ timeout: 5000 }).catch((e) => logs.push('click ' + e.message.slice(0, 80))); await win.waitForTimeout(300);
await win.evaluate(() => document.activeElement && document.activeElement.blur());
await shot('01-frames');
await win.locator('#mobileTabs button').nth(1).click();
await win.waitForTimeout(3000);
await shot('02-frame');
await win.evaluate(() => document.querySelector('#inspector').scrollTop = 700);
await shot('03-frame-scrolled');
await win.locator('button', { hasText: '＋ Добавить фильтр' }).click().catch((e) => logs.push('flt ' + e.message.slice(0, 80))); await win.waitForTimeout(400);
await win.locator('button', { hasText: '＋ Ещё фильтр' }).click().catch((e) => logs.push('flt2 ' + e.message.slice(0, 80))); await win.waitForTimeout(400);
await win.locator('.eff-item select').nth(1).selectOption('tint').catch(() => {}); await win.waitForTimeout(400);
await win.locator('.eff-item').first().scrollIntoViewIfNeeded().catch(() => {});
await shot('03b-filters');
await win.locator('.eff-item button', { hasText: '✕' }).first().click().catch(() => {}); await win.waitForTimeout(300);
await win.locator('.eff-item button', { hasText: '✕' }).first().click().catch(() => {}); await win.waitForTimeout(300);
await win.locator('[data-menu="file"]').click();
await shot('04-filemenu');
await esc();
await win.locator('#btnLibrary').click(); await win.waitForTimeout(1200);
await shot('05-library');
await win.locator('.lib-list .grid > *').first().click().catch(() => {}); await win.waitForTimeout(800);
await shot('06-library-edit');
await win.evaluate(() => document.querySelector('.lib-edit').scrollTop = 900);
await shot('06b-library-edit-poses');
await win.locator('.lib-edit-back button').click().catch((e) => logs.push('back ' + e.message.slice(0, 60)));
await shot('06c-library-back');
await esc();
await win.locator('#btnScenes').click(); await win.waitForTimeout(800);
await shot('07-scenes');
await esc();
await win.locator('#btnSettings').click(); await win.waitForTimeout(800);
await shot('08-settings');
await esc();
await win.locator('#btnExport').click(); await win.waitForTimeout(800);
await shot('09-export');
await esc();

console.log(logs.join('\n'));
await app.close();

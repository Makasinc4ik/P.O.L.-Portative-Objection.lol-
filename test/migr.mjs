import fs from 'fs';
const ROOT = '/home/claude/oo', OUT = ROOT + '/test/out';
const LIB = process.env.LIB;
const app = await electron.launch({ executablePath: ROOT + '/node_modules/electron/dist/electron', args: ['--no-sandbox', ROOT], env: { ...process.env, OO_LIBRARY: LIB } });
const win = await app.firstWindow();
